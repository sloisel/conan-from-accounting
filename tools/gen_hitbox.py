#!/usr/bin/env python3
"""Generate hitbox.s: when does the sword hit a monster?

For each sword frame (directions S, SE, E, NE, N, NW, W, SW = player_dir_nz
1..8, frames 41..48) the bounding box of the blade's pixels, and for each
monster type the bounding box of its pixels (all its frames). The sword
hits when the two boxes overlap. With d = monster position - sword sprite
position (pixels), that is an interval per axis:
    blade_x0 - monster_x1  <=  dx  <=  blade_x1 - monster_x0
stored biased by +128 as [min, end) so the 6502 compares unsigned.

Usage: python3 tools/gen_hitbox.py > hitbox.s
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SWORD = list(range(41, 49))                      # player_dir_nz 1..8
TYPES = [("blob", range(49, 53)), ("skeleton", range(53, 65)), ("ghost", range(79, 83)),
         ("cyclops", range(65, 73)), ("jelly", range(73, 78))]
# controller numbers 4, 6, 8, 10, 12 -> table block (controller - 4) / 2
ORDER = ["blob", "skeleton", "ghost", "cyclops", "jelly"]


def sprites():
    t = open(os.path.join(ROOT, "mysprites.txt")).read()
    parts = re.split(r"// sprite (\d+) / (\w+) / color: \$([0-9a-f]+)", t)[1:]
    out = {}
    for i in range(0, len(parts), 4):
        n, mode, col, body = parts[i:i + 4]
        out[int(n)] = (mode, [int(x, 16) for x in re.findall(r"\$([0-9a-f]{2})", body)][:63])
    return out


def bbox(spr, frames):
    xs, ys = [], []
    for f in frames:
        mode, d = spr[f]
        for r in range(21):
            for c in range(24):
                b = d[r * 3 + c // 8]
                on = (b >> (6 - ((c % 8) & 6))) & 3 if mode == "multicolor" else b & (0x80 >> (c % 8))
                if on:
                    xs.append(c)
                    ys.append(r)
    return min(xs), max(xs), min(ys), max(ys)


def main():
    spr = sprites()
    types = dict(TYPES)
    rows = {k: [] for k in ("xmin", "xend", "ymin", "yend")}
    print("// generated by tools/gen_hitbox.py from mysprites.txt -- rerun instead of editing")
    print("// sword hit boxes: index = (controller - 4) * 4 + player_dir_nz - 1, values + 128")
    for name in ORDER:
        mx0, mx1, my0, my1 = bbox(spr, types[name])
        print(f"//   {name}: body x {mx0}..{mx1}, y {my0}..{my1}")
        for f in SWORD:
            bx0, bx1, by0, by1 = bbox(spr, [f])
            rows["xmin"].append(bx0 - mx1 + 128)
            rows["xend"].append(bx1 - mx0 + 129)
            rows["ymin"].append(by0 - my1 + 128)
            rows["yend"].append(by1 - my0 + 129)
    print(".segment TABLES")
    for k, v in rows.items():
        print(f"hb_{k}: .byte " + ",".join(str(x) for x in v))


if __name__ == "__main__":
    main()
