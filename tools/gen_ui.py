#!/usr/bin/env python3
"""Generate uigfx.s: sprite pictures for the status strip and the items,
and Conan lying dead (face up, X eyes) at the end of his death spin.

Multicolour sprites, 12 double-width pixels x 21 rows: '.' transparent,
'k' multicolour 1 (black outline), 'r' the sprite's own colour, 'w'
multicolour 2 (white). The pictures sit in the bottom rows of the sprite,
so in the status strip (sprite y = UI_Y) they end just above the timed raster
code at line 37.

Usage: python3 tools/gen_ui.py > uigfx.s
"""

HEART = [
    "..kk.kk.....",
    ".krrkrrk....",
    ".kwrrrrk....",
    ".krrrrrk....",
    ".krrrrrk....",
    "..krrrk.....",
    "..krrrk.....",
    "...krk......",
    "....k.......",
]
KEY = [
    "..kkk.......",
    ".krrrk......",
    ".kr.rk......",
    ".krrrk......",
    "..krk.......",
    "..krk.......",
    "..krrk......",
    "..krk.......",
    "..krrk......",
    "..kk........",
]
DEAD = [                      # (full height; colour: Conan's skin)
    "..kkkkkkkk..",
    ".kkwkrrkwkk.",
    "krwkwrrwkwrk",
    "krkwkrrkwkrk",
    "krrrrrrrrrrk",
    "krrrrrrrrrrk",
    "krrrkkkkrrrk",
    "krrkkkkkkrrk",
    "krrkkrrkkrrk",
    "krrrkrrkrrrk",
    ".krrrrrrrrk.",
    "..krrrrrrk..",
    "kkwkkkkkkwkk",
    "kwwkwrrwkwwk",
    "krrkwrrwkrrk",
    "kkkkwrrwkkkk",
    "...kwwwwk...",
    "..kwwwwwwk..",
    ".kwwk..kwwk.",
    "kwwk....kwwk",
    "kkk......kkk",
]
CODE = {".": 0, "k": 1, "r": 2, "w": 3}


def block(rows):
    rows = ["." * 12] * (21 - len(rows)) + rows       # bottom aligned
    out = []
    for r in rows:
        assert len(r) == 12, r
        for b in range(3):
            v = 0
            for c in r[4 * b: 4 * b + 4]:
                v = v << 2 | CODE[c]
            out.append(v)
    return out + [0]


def main():
    print("// generated by tools/gen_ui.py -- rerun instead of editing")
    print("// 64-byte sprite blocks: heart, key (x3, one per key colour), Conan dead")
    for name, rows in (("heart", HEART), ("key", KEY), ("key", KEY), ("key", KEY), ("dead", DEAD)):
        data = block(rows)
        print(f"    // {name}")
        for i in range(0, 64, 16):
            print("    .byte " + ",".join(f"${x:02x}" for x in data[i:i + 16]))


if __name__ == "__main__":
    main()
