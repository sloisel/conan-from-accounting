#!/usr/bin/env python3
"""Generate spawns.s: where monsters live on the map.

The map has a single route (the hedge + lake wall off the west meadow and
the river has one bridge):
  start pocket (the old wizard hands over the sword) -> south strip
  -> graveyard -> gravel plateau -> NE forest -> bridge -> west meadow
  -> pond in the NW, where the princess waits behind her guards.
Each zone gets monster types matching its biome, with density rising along
the route. The tile-0 "1" markers drawn in the map editor become blob
spawns (the game turns those tiles back into grass at start-up).

Usage: python3 tools/gen_spawns.py > spawns.s
"""
import os
import random
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# monster types = controller numbers in mycontrol.s
BLOB, SKEL, GHOST, CYCL, JELLY, WIZ, PRIN = 4, 6, 8, 10, 12, 14, 16
NAMES = {BLOB: "blob", SKEL: "skeleton", GHOST: "ghost", CYCL: "cyclops",
         JELLY: "jelly", WIZ: "wizard", PRIN: "princess"}

START = (2, 61)                # player start tile


def load():
    s = open(os.path.join(ROOT, "ultimate.s")).read()
    seg = lambda n: s.split(".segment " + n)[1].split(".segment")[0]
    nums = lambda t: [int(x, 16) for x in re.findall(r"\$([0-9A-Fa-f]+)", t)]
    return nums(seg("MAP")), nums(seg("TILETAG"))


# zone: (name, test(tx, ty), [types to draw from], tiles per monster)
ZONES = [
    ("pond", lambda x, y: x < 12 and y < 12, [CYCL, JELLY], 9),
    ("start + south strip", lambda x, y: x < 48 and y >= 48, [BLOB], 45),
    ("south-east grass", lambda x, y: x >= 48 and y >= 57, [BLOB, BLOB, SKEL], 30),
    ("graveyard", lambda x, y: x >= 48 and 40 <= y < 57, [SKEL, SKEL, GHOST], 22),
    ("gravel plateau", lambda x, y: x >= 48 and 28 <= y < 40, [CYCL, SKEL], 24),
    ("north-east forest", lambda x, y: x >= 40 and y < 28, [CYCL, BLOB, SKEL], 26),
    ("west meadow", lambda x, y: x < 38 and y < 42, [JELLY, JELLY, GHOST, SKEL, CYCL], 24),
]


def main():
    mp, tag = load()
    walk = lambda x, y: 0 <= x < 64 and 0 <= y < 64 and tag[mp[y * 64 + x]] in (0x80, 0x81, 0x82, 0x83, 0x84, 0x04)
    rnd = random.Random(1964)
    spawns = []                                    # (tx, ty, type, zone)

    def free(x, y, gap):
        return all(max(abs(x - a), abs(y - b)) >= gap for a, b, _, _ in spawns)

    # the map editor's "1" markers: the one farthest up the start pocket is
    # the old wizard (you run past the other markers' blobs to reach him)
    markers = [(x, y) for y in range(64) for x in range(64) if tag[mp[y * 64 + x]] == 0x04]
    wizard = max(markers, key=lambda p: (p[0] - START[0]) ** 2 + (p[1] - START[1]) ** 2)
    for x, y in markers:
        spawns.append((x, y, WIZ, "start: wizard") if (x, y) == wizard else (x, y, BLOB, "marker"))

    # the princess in the far corner of the pond area
    def nearest(x0, y0):
        return min(((x, y) for y in range(64) for x in range(64) if walk(x, y) and tag[mp[y * 64 + x]] != 4),
                   key=lambda p: (p[0] - x0) ** 2 + (p[1] - y0) ** 2)
    px, py = nearest(2, 2)
    spawns.append((px, py, PRIN, "pond"))

    for name, test, types, per in ZONES:
        if not types:
            continue
        cells = [(x, y) for y in range(64) for x in range(64)
                 if walk(x, y) and test(x, y)
                 and next(n for n, t, _, _ in ZONES if t(x, y)) == name]
        rnd.shuffle(cells)
        want = max(1, len(cells) // per)
        placed = 0
        for x, y in cells:
            if placed >= want:
                break
            gap = 3 if name == "pond" else 4
            if max(abs(x - START[0]), abs(y - START[1])) < 6 or not free(x, y, gap):
                continue
            spawns.append((x, y, types[placed % len(types)], name))
            placed += 1

    print("// generated by tools/gen_spawns.py -- do not edit, rerun instead")
    print("// monster spawn points: tile x, tile y, type (controller number)")
    for name in ["marker", "start: wizard"] + [z[0] for z in ZONES]:
        zs = [s for s in spawns if s[3] == name]
        if zs:
            kinds = {}
            for s in zs:
                kinds[NAMES[s[2]]] = kinds.get(NAMES[s[2]], 0) + 1
            print(f"//   {name}: " + ", ".join(f"{v} {k}" for k, v in kinds.items()))
    print(".segment TABLES")
    print(f".const SPAWN_N = {len(spawns)}")
    per = 4
    print(f".const SPAWN_PER_FRAME = {per}          // spawn points checked per frame")
    print(f".const SPAWN_GRACE = {-(-len(spawns) // per) + 2}             "
          f"// frames after a full redraw in which monsters may spawn in view (one sweep)")
    for field, i in (("spawn_tx", 0), ("spawn_ty", 1), ("spawn_type", 2)):
        print(f"{field}: .byte " + ",".join(str(s[i]) for s in spawns))
    for field, i in (("spawn_cx", 0), ("spawn_cy", 1)):    # tile centre in chars
        print(f"{field}: .byte " + ",".join(str(s[i] * 4 + 2) for s in spawns))
    print("spawn_state: .fill SPAWN_N, 0   // 0 idle, 1 active, 2 dead")


if __name__ == "__main__":
    main()
